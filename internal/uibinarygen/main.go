// uibinarygen generates typed KUI1 field operations. Reflection is never linked
// into the runtime codec. Declaration order is the versioned binary layout.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
)

func main() {
	models := readModels()

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by internal/uibinarygen; DO NOT EDIT.\npackage ui")

	for _, name := range []string{"Template", "Element", "Style", "Image", "Length"} {
		model := models[name]
		if model == nil {
			panic(name)
		}

		writeModel(&output, name, model)
	}

	encoded, err := format.Source(output.Bytes())
	if err != nil {
		panic(err)
	}

	if err := os.WriteFile("binary_fields.gen.go", encoded, 0o600); err != nil {
		panic(err)
	}
}

func readModels() map[string]*ast.StructType {
	models := map[string]*ast.StructType{}

	for _, name := range []string{"template.go", "sizing.go"} {
		file, err := parser.ParseFile(token.NewFileSet(), name, nil, 0)
		if err != nil {
			panic(err)
		}

		collectModels(file, models)
	}

	return models
}

func collectModels(file *ast.File, models map[string]*ast.StructType) {
	for _, decl := range file.Decls {
		group, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}

		for _, spec := range group.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}

			if model, ok := typeSpec.Type.(*ast.StructType); ok {
				models[typeSpec.Name.Name] = model
			}
		}
	}
}

func writeModel(output *bytes.Buffer, name string, model *ast.StructType) {
	fmt.Fprintf(output, "func (w *uiWriter) write%s(v %s) {\n", name, name)

	for _, field := range model.Fields.List {
		for _, identifier := range field.Names {
			fmt.Fprintf(output, "w.write%s(v.%s)\n", operation(field.Type), identifier.Name)
		}
	}

	fmt.Fprintln(output, "}")
	fmt.Fprintf(output, "func (r *uiReader) read%s() %s { var v %s\n", name, name, name)

	for _, field := range model.Fields.List {
		for _, identifier := range field.Names {
			fmt.Fprintf(output, "v.%s = r.read%s()\n", identifier.Name, operation(field.Type))
		}
	}

	fmt.Fprintln(output, "return v\n}")
}

func operation(expr ast.Expr) string {
	switch typed := expr.(type) {
	case *ast.Ident:
		switch typed.Name {
		case "uint8":
			return "U8"
		case "uint16":
			return "U16"
		case "uint32":
			return "U32"
		case "int32":
			return "I32"
		case "bool":
			return "Bool"
		case "string":
			return "String"
		default:
			return typed.Name
		}
	case *ast.ArrayType:
		if typed.Len == nil {
			if element, ok := typed.Elt.(*ast.Ident); ok && element.Name == "Element" {
				return "Elements"
			}
		}
	}

	panic("unsupported binary UI field type")
}
